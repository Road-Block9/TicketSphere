@app.get("/health", tags=["System"])
def health_check():
    """Health check endpoint to verify mock API server availability."""
    return {
        "status": "healthy",
        "service": "Simulated Enterprise Support REST API",
        "version": "1.0.0",
        "data_mode": "SIMULATED_DEMONSTRATION",
        "note": "Clearly identified as simulated local test data for Capstone requirements."
    }


@app.get("/api/v1/tickets", tags=["Tickets"])
def get_tickets(
    status_filter: Optional[str] = Query(None, alias="status", description="Filter tickets by status (e.g. Open, Resolved)"),
    limit: int = Query(50, ge=1, le=100, description="Max tickets to retrieve"),
    x_api_key: Optional[str] = Header(None, description="Optional API Authentication Key")
):
    """
    Retrieves support tickets in standard JSON payload format.
    Supports optional status filtering and API Key verification.
    """
    # Verify API Key if one was supplied
    if x_api_key is not None and x_api_key != EXPECTED_API_KEY:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Invalid or unauthorized API key provided."
        )

    # Filter by status if requested
    tickets = MOCK_API_TICKETS
    if status_filter:
        tickets = [t for t in tickets if t["status"].lower() == status_filter.strip().lower()]

    paginated = tickets[:limit]

    return {
        "status": "success",
        "source": "SIMULATED_ENTERPRISE_API",
        "total_available": len(MOCK_API_TICKETS),
        "count": len(paginated),
        "tickets": paginated
    }


def run_mock_server(host: str = "127.0.0.1", port: int = 8000):
    """Runs the FastAPI server using Uvicorn."""
    import uvicorn
    print(f"Starting Mock Support Ticket REST API at http://{host}:{port}")
    print(f"Swagger Documentation available at http://{host}:{port}/docs")
    uvicorn.run(app, host=host, port=port, log_level="info")


if __name__ == "__main__":
    run_mock_server()
